function renderErrorsPage(ctx) {
  const lines = pageHeader(
    'Errors',
    'Every non-2xx response from the control API has the same body, and the ingest endpoint on the ' +
      'data plane uses the same envelope and the same codes (see [Ingest](./01-ingest.md) for the ' +
      'codes it emits). Branch on `error.code`, never on `error.message`; quote `error.request_id` ' +
      'when you ask for help.',
  );

  const envelopeName = 'ApiErrorResponse';
  const envelope = ctx.schemas[envelopeName];
  lines.push('## The envelope', '');
  if (envelope) {
    const schema = ctx.effective(envelope);
    if (schema.description) lines.push(escapeText(schema.description), '');
    lines.push('```json', JSON.stringify(exampleOf(ctx, schema), null, 2), '```', '');
    lines.push(...propertyTable(ctx, schema));
  } else {
    lines.push(`The document declares no \`${envelopeName}\` schema.`, '');
  }

  lines.push('## Codes', '');
  lines.push(
    'The status column is the HTTP status the code is returned with, as documented on the operations ' +
      'that name it. "Operations" counts the control-API operations whose responses list the code; the ' +
      'ingest endpoint is not in this document and is not counted. Two things the per-operation lists ' +
      'do not repeat: every operation that takes a body or query parameters can answer ' +
      '`400 invalid_request` when validation fails, and every operation can answer `500 internal_error`.',
    '',
  );
  const codes = enumeratedErrorCodes(ctx, envelope);
  const index = ctx.errorCodeIndex();
  lines.push('| Code | Status | Operations |', '|---|---|---|');
  for (const code of codes) {
    const entry = index.get(code);
    const observed = entry ? [...entry.statuses].sort((a, b) => a - b) : [];
    const statuses = observed.length > 0 ? observed : FALLBACK_CODE_STATUS[code] !== undefined ? [FALLBACK_CODE_STATUS[code]] : [];
    const statusText = statuses.length > 0 ? statuses.map((s) => `${s} ${HTTP_STATUS_TEXT[s] || ''}`.trim()).join(', ') : '-';
    lines.push(`| [\`${code}\`](#${code.replace(/_/g, '-')}) | ${statusText} | ${entry ? entry.operations : 0} |`);
  }
  lines.push('');

  for (const code of codes) {
    lines.push(`### ${code}`, '');
    const entry = index.get(code);
    const statuses = entry ? [...entry.statuses].sort((a, b) => a - b) : FALLBACK_CODE_STATUS[code] !== undefined ? [FALLBACK_CODE_STATUS[code]] : [];
    if (statuses.length > 0) lines.push(`HTTP ${statuses.map((s) => `${s} ${HTTP_STATUS_TEXT[s] || ''}`.trim()).join(' or ')}.`, '');
    if (CODE_MEANINGS[code]) lines.push(escapeText(CODE_MEANINGS[code]), '');
    const detail = detailsFor(ctx, envelope, code);
    if (detail.length > 0) {
      lines.push('`error.details` carries:', '');
      lines.push('| Field | Type | Description |', '|---|---|---|');
      for (const d of detail) lines.push(`| \`${d.name}\` | ${d.type} | ${escapeCell(d.description)} |`);
      lines.push('');
    }
  }
  return lines.join('\n');
}

/** The `error.code` enum, straight from the envelope schema; fallback keys if absent. */
function enumeratedErrorCodes(ctx, envelope) {
  const codeSchema = envelope && envelope.properties && envelope.properties.error && envelope.properties.error.properties && envelope.properties.error.properties.code;
  const fromDocument = codeSchema && Array.isArray(codeSchema.enum) ? codeSchema.enum.map(String) : [];
  const observed = [...ctx.errorCodeIndex().keys()];
  const all = [...fromDocument];
  for (const code of observed) if (!all.includes(code)) all.push(code);
  return all;
}

/**
 * The `details` properties the envelope schema attributes to a code. Detected
 * from each property's description naming the code - the schema has no other
 * way to say "this key appears on that code".
 */
function detailsFor(ctx, envelope, code) {
  const details = envelope && envelope.properties && envelope.properties.error && envelope.properties.error.properties && envelope.properties.error.properties.details;
  if (!details || !details.properties) return [];
  const out = [];
  for (const [name, prop] of Object.entries(details.properties)) {
    const description = String(prop.description || '');
    if (description.includes(`\`${code}\``)) {
      out.push({ name, type: typeText(ctx, ctx.effective(prop)), description });
    }
  }
  return out;
}

/** A representative body: examples where the schema has them, first enum value, type placeholder. */
function exampleOf(ctx, schema, depth = 0) {
  const s = ctx.effective(schema);
  if (s.example !== undefined) return s.example;
  if (Array.isArray(s.enum) && s.enum.length > 0) return s.enum[0];
  if (Array.isArray(s.oneOf) && s.oneOf.length > 0) return exampleOf(ctx, s.oneOf[0], depth + 1);
  if (s.properties && depth < 4) {
    const out = {};
    for (const [name, prop] of Object.entries(s.properties)) {
      if (name === 'details') continue; // absent on most errors, and its shape is per-code
      out[name] = exampleOf(ctx, prop, depth + 1);
    }
    return out;
  }
  switch (s.type) {
    case 'string':
      return s.format === 'date-time' ? '2026-01-01T00:00:00.000Z' : 'string';
    case 'number':
    case 'integer':
      return 0;
    case 'boolean':
      return false;
    case 'array':
      return [];
    default:
      return null;
  }
}

