/** @returns {Map<string, string>} filename -> content, in page order */
function render(document) {
  const ctx = new Context(document);
  const pages = new Map();

  const tags = orderedTags(ctx.operationsByTag());
  tags.forEach((tag, index) => {
    const number = String(index + FIRST_PAGE_NUMBER).padStart(2, '0');
    pages.set(`${number}-${tag}.md`, renderTagPage(ctx, tag, ctx.operationsByTag().get(tag)));
  });
  pages.set('errors.md', renderErrorsPage(ctx));
  pages.set('schemas.md', renderSchemasPage(ctx));
  return pages;
}

function orderedTags(byTag) {
  const present = new Set(byTag.keys());
  const known = TAG_ORDER.filter((t) => present.has(t) && t !== 'auth');
  const extra = [...present].filter((t) => !TAG_ORDER.includes(t)).sort();
  const tail = present.has('auth') ? ['auth'] : [];
  return [...known, ...extra, ...tail];
}

class Context {
  constructor(document) {
    this.document = document;
    this.schemas = (document.components && document.components.schemas) || {};
    this._byTag = null;
  }

  /** @returns {Map<string, Operation[]>} in document order, untagged under "other" */
  operationsByTag() {
    if (this._byTag) return this._byTag;
    const byTag = new Map();
    for (const [route, item] of Object.entries(this.document.paths)) {
      if (!item || typeof item !== 'object') continue;
      const methods = Object.keys(item)
        .filter((m) => METHOD_ORDER.includes(m.toLowerCase()))
        .sort((a, b) => METHOD_ORDER.indexOf(a.toLowerCase()) - METHOD_ORDER.indexOf(b.toLowerCase()));
      for (const method of methods) {
        const op = item[method];
        if (!op || typeof op !== 'object') continue;
        const tag = Array.isArray(op.tags) && op.tags.length > 0 ? String(op.tags[0]) : 'other';
        if (!byTag.has(tag)) byTag.set(tag, []);
        byTag.get(tag).push({ method: method.toUpperCase(), route, op, pathItem: item });
      }
    }
    this._byTag = byTag;
    return byTag;
  }

  /** Follow `$ref` chains; returns [name|null, schema]. */
  resolve(schema, depth = 0) {
    if (!schema || typeof schema !== 'object' || depth > 10) return [null, schema || {}];
    if (typeof schema.$ref === 'string') {
      const name = schema.$ref.replace(/^#\/components\/schemas\//, '');
      const target = this.schemas[name];
      if (!target) return [name, {}];
      const [innerName, inner] = this.resolve(target, depth + 1);
      return [innerName || name, inner];
    }
    return [null, schema];
  }

  /**
   * Flatten `allOf` (the pattern NestJS emits for a typed `$ref` property with
   * its own description) and resolve refs, keeping the outer description,
   * nullability and constraints.
   */
  effective(schema) {
    const [name, base] = this.resolve(schema);
    let merged = { ...base };
    let refName = name;
    if (Array.isArray(base.allOf)) {
      merged = {};
      for (const part of base.allOf) {
        const [partName, partSchema] = this.resolve(part);
        const eff = this.effective(partSchema);
        if (partName && !refName) refName = partName;
        if (eff.refName && !refName) refName = eff.refName;
        merged = mergeSchemas(merged, eff);
      }
      const { allOf: _drop, ...rest } = base;
      merged = mergeSchemas(merged, rest);
    }
    if (schema && typeof schema === 'object' && !schema.$ref) {
      // Outer overrides: description/nullable/example on the property itself.
      for (const key of ['description', 'nullable', 'example', 'default', 'deprecated']) {
        if (schema[key] !== undefined) merged[key] = schema[key];
      }
    }
    if (refName && (merged.properties || merged.enum || merged.type)) merged.refName = refName;
    return merged;
  }

  /** Where each error code appears, derived from the responses. */
  errorCodeIndex() {
    const index = new Map(); // code -> { statuses:Set<number>, operations:number }
    for (const [, operations] of this.operationsByTag()) {
      for (const { op } of operations) {
        const seen = new Set();
        for (const [status, response] of Object.entries(op.responses || {})) {
          const code = Number(status);
          if (!Number.isInteger(code) || code < 400) continue;
          for (const errorCode of errorCodesIn(response && response.description)) {
            if (!index.has(errorCode)) index.set(errorCode, { statuses: new Set(), operations: 0 });
            index.get(errorCode).statuses.add(code);
            seen.add(errorCode);
          }
        }
        for (const errorCode of seen) index.get(errorCode).operations += 1;
      }
    }
    return index;
  }
}

function mergeSchemas(a, b) {
  const out = { ...a, ...b };
  if (a.properties || b.properties) out.properties = { ...(a.properties || {}), ...(b.properties || {}) };
  if (a.required || b.required) out.required = [...new Set([...(a.required || []), ...(b.required || [])])];
  return out;
}

