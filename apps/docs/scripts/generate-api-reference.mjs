// Pages
// ---------------------------------------------------------------------------

function pageHeader(title, intro) {
  return [GENERATED_MARKER, '', `# ${title}`, '', GENERATED_NOTE, '', ...(intro ? [intro, ''] : [])];
}

function renderTagPage(ctx, tag, operations) {
  const title = TAG_TITLES[tag] || titleCase(tag);
  const lines = pageHeader(title);

  lines.push('| Operation | Summary |', '|---|---|');
  for (const { method, route, op } of operations) {
    lines.push(`| [${method} \`${escapeCell(route)}\`](#${operationAnchor(method, route)}) | ${escapeCell(op.summary || '')} |`);
  }
  lines.push('');

  for (const operation of operations) lines.push(...renderOperation(ctx, operation));
  return lines.join('\n');
}

/**
 * The H3 is `METHOD /path`, so the anchor is derived from the route alone and
 * survives every edit to summaries and descriptions. VitePress slugifies it to
 * `method-v1-projects-projectid-endpoints`; `operationAnchor` mirrors that.
 */
function renderOperation(ctx, { method, route, op, pathItem }) {
  const lines = [];
  lines.push(`### ${method} \`${route}\``, '');
  if (op.summary) lines.push(`**${escapeText(op.summary)}**`, '');
  if (op.deprecated) lines.push('> Deprecated.', '');
  if (op.description) lines.push(escapeText(op.description), '');

  lines.push(`**Auth:** ${authText(ctx, op)}`, '');

  const params = collectParameters(ctx, route, op, pathItem);
  if (params.length > 0) {
    lines.push('#### Parameters', '');
    lines.push('| Name | In | Type | Required | Constraints | Description |', '|---|---|---|---|---|---|');
    for (const p of params) {
      const schema = ctx.effective(p.schema || {});
      lines.push(
        `| \`${escapeCell(p.name)}\` | ${p.in} | ${typeText(ctx, schema, p.in === 'path' ? 'string' : undefined)} | ` +
          `${p.required ? 'yes' : 'no'} | ${escapeCell(constraintsText(schema))} | ${escapeCell(p.description || '')} |`,
      );
    }
    lines.push('');
  }

  const body = op.requestBody && op.requestBody.content && op.requestBody.content['application/json'];
  if (body && body.schema) {
    const [name] = ctx.resolve(body.schema);
    const schema = ctx.effective(body.schema);
    const required = op.requestBody.required ? 'required' : 'optional';
    lines.push('#### Request body', '');
    lines.push(`\`application/json\`, ${required}${name ? ` - ${schemaLink(name)}` : ''}${schema.description ? `. ${escapeText(schema.description)}` : ''}`, '');
    lines.push(...propertyTable(ctx, schema));
  }

  lines.push('#### Responses', '');
  const statuses = Object.keys(op.responses || {}).sort(compareStatus);
  for (const status of statuses) {
    const response = op.responses[status] || {};
    const content = response.content && response.content['application/json'];
    const schemaRef = content && content.schema;
    const [name] = schemaRef ? ctx.resolve(schemaRef) : [null];
    const code = Number(status);
    const isError = Number.isInteger(code) && code >= 400;

    const { text, codes } = splitErrorCodes(response.description || '');
    const label = HTTP_STATUS_TEXT[code] ? `${status} ${HTTP_STATUS_TEXT[code]}` : status;
    const head = [`**${label}**`];
    if (name) head.push(`- ${schemaLink(name)}`);
    else if (!schemaRef && code === 204) head.push('- no body');
    lines.push(head.join(' '), '');
    if (text) lines.push(escapeText(text), '');

    if (isError) {
      if (codes.length > 0) {
        lines.push(`\`error.code\`: ${codes.map(errorCodeLink).join(', ')}`, '');
      } else {
        lines.push('See [errors](./errors.md) for the envelope and the codes.', '');
      }
    } else if (schemaRef) {
      lines.push(...propertyTable(ctx, ctx.effective(schemaRef)));
    }
  }
  return lines;
}

function compareStatus(a, b) {
  const na = Number(a);
  const nb = Number(b);
  if (Number.isNaN(na) || Number.isNaN(nb)) return String(a).localeCompare(String(b));
  return na - nb;
}

/**
 * Path parameters first, then query, each in document order. A path
 * parameter the template names but the operation never declares (NestJS emits
 * none for a controller-level `:projectId`) is synthesised so the table is
 * still complete; it renders as a required string with no description.
 */
function collectParameters(ctx, route, op, pathItem) {
  const declared = [...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []), ...(Array.isArray(op.parameters) ? op.parameters : [])]
    .map((p) => (p && p.$ref ? resolveParameterRef(ctx, p) : p))
    .filter((p) => p && typeof p === 'object' && p.name);
  const byKey = new Map();
  for (const p of declared) byKey.set(`${p.in}:${p.name}`, p);

  const pathParams = [];
  for (const match of route.matchAll(/\{([^}]+)\}/g)) {
    const name = match[1];
    pathParams.push(byKey.get(`path:${name}`) || { name, in: 'path', required: true, schema: { type: 'string' } });
  }
  const others = [...byKey.values()].filter((p) => p.in !== 'path');
  return [...pathParams, ...others];
}

function resolveParameterRef(ctx, p) {
  const name = String(p.$ref).replace(/^#\/components\/parameters\//, '');
  const params = (ctx.document.components && ctx.document.components.parameters) || {};
  return params[name] || null;
}

function authText(ctx, op) {
  const security = Array.isArray(op.security) ? op.security : ctx.document.security;
  if (!Array.isArray(security) || security.length === 0) return 'none - this route is public.';
  const alternatives = security
    .map((requirement) =>
      Object.keys(requirement || {})
        .map((scheme) => SECURITY_LABELS[scheme] || `\`${scheme}\``)
        .join(' and '),
    )
    .filter(Boolean);
  const unique = [...new Set(alternatives)];
  if (unique.length === 0) return 'none - this route is public.';
  return unique.length === 1 ? `${unique[0]}.` : `either ${unique.join(', or ')}.`;
}

