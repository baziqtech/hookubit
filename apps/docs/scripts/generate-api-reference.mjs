function renderSchemasPage(ctx) {
  const lines = pageHeader(
    'Schemas',
    'Every request and response body in the control API, by name. Operation pages link here for the ' +
      'shape of anything they reference more than one level deep.',
  );
  const names = Object.keys(ctx.schemas).sort((a, b) => a.localeCompare(b));
  lines.push('| Schema | Kind |', '|---|---|');
  for (const name of names) {
    lines.push(`| [\`${name}\`](#${name.toLowerCase()}) | ${schemaKind(ctx, ctx.schemas[name])} |`);
  }
  lines.push('');
  for (const name of names) {
    const schema = ctx.effective(ctx.schemas[name]);
    lines.push(`### ${name}`, '');
    if (schema.description) lines.push(escapeText(schema.description), '');
    if (Array.isArray(schema.enum)) {
      lines.push(`${typeText(ctx, { ...schema, enum: undefined })} enum: ${schema.enum.map((v) => `\`${escapeText(String(v))}\``).join(', ')}`, '');
    } else if (schema.properties) {
      lines.push(...propertyTable(ctx, schema));
    } else {
      lines.push(`Type: ${typeText(ctx, schema)}${constraintsText(schema) ? ` (${escapeText(constraintsText(schema))})` : ''}`, '');
    }
  }
  return lines.join('\n');
}

function schemaKind(ctx, raw) {
  const schema = ctx.effective(raw);
  if (Array.isArray(schema.enum)) return 'enum';
  if (schema.properties) return 'object';
  return typeText(ctx, schema);
}

