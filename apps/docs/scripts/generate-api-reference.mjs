#!/usr/bin/env node
/**
 * Generates the customer-facing API reference under apps/docs/api/ from the
 * control plane's OpenAPI document.
 *
 *   node scripts/generate-api-reference.mjs           write pages that changed
 *   node scripts/generate-api-reference.mjs --check   exit 1 if the pages on disk
 *                                                     differ from what the source
 *                                                     would produce (CI drift check)
 *
 * # Why generated
 *
 * A hand-written reference is confidently wrong within a month. The OpenAPI
 * document is emitted from the controllers and DTOs the product is built from,
 * the dashboard's client is generated from the same file, so a page rendered
 * from it cannot describe a route or a field that does not exist. When the
 * output reads badly, fix the decorator at the source - never the page.
 *
 * # Rules
 *
 * - Plain Node, ESM, no dependencies. It must run on a laptop with nothing
 *   installed but Node, because it runs before the docs' own dependencies do.
 * - Deterministic: same input, byte-identical output. No timestamps, no
 *   environment-dependent text, stable ordering everywhere. That is what makes
 *   --check meaningful.
 * - Robust: an OpenAPI construct this file has no rule for renders as its JSON
 *   type rather than aborting the build. A missing or malformed document is a
 *   loud, non-zero exit.
 * - Verbatim: summaries and descriptions are copied as written. They are
 *   customer-facing text owned by the DTO decorators.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const SCRIPT_DIR = path.dirname(new URL(import.meta.url).pathname);
const DOCS_DIR = path.resolve(SCRIPT_DIR, '..');
const REPO_ROOT = path.resolve(DOCS_DIR, '..', '..');
const SOURCE = path.join(REPO_ROOT, 'apps', 'control-api', 'openapi.json');
const OUT_DIR = path.join(DOCS_DIR, 'api');

