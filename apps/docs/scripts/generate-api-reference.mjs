/**
 * One row per property. Objects one level down are flattened to `parent.child`;
 * arrays of objects to `parent[].child`. Anything deeper shows its type and a
 * link to the schema page.
 */
function propertyTable(ctx, schema) {
  const rows = propertyRows(ctx, schema, '', 0);
  if (rows.length === 0) {
    if (schema.additionalProperties) return [`A free-form object: ${typeText(ctx, schema)}.`, ''];
    if (Array.isArray(schema.enum)) return [`One of: ${schema.enum.map((v) => `\`${escapeText(String(v))}\``).join(', ')}.`, ''];
    if (schema.type && schema.type !== 'object') return [`Type: ${typeText(ctx, schema)}.`, ''];
    return ['No documented properties.', ''];
  }
  const lines = ['| Property | Type | Required | Constraints | Description |', '|---|---|---|---|---|'];
  for (const r of rows) {
    lines.push(`| \`${escapeCell(r.name)}\` | ${r.type} | ${r.required ? 'yes' : 'no'} | ${escapeCell(r.constraints)} | ${escapeCell(r.description)} |`);
  }
  lines.push('');
  return lines;
}

function propertyRows(ctx, schema, prefix, depth) {
  const rows = [];
  const properties = schema.properties || {};
  const required = new Set(Array.isArray(schema.required) ? schema.required : []);
  for (const [name, raw] of Object.entries(properties)) {
    const prop = ctx.effective(raw);
    rows.push({
      name: `${prefix}${name}`,
      type: typeText(ctx, prop),
      required: required.has(name),
      constraints: constraintsText(prop),
      description: prop.description || '',
    });
    if (depth > 0) continue;
    if (prop.properties) {
      rows.push(...propertyRows(ctx, prop, `${prefix}${name}.`, depth + 1));
    } else if (prop.type === 'array' && prop.items) {
      const items = ctx.effective(prop.items);
      if (items.properties) rows.push(...propertyRows(ctx, items, `${prefix}${name}[].`, depth + 1));
    }
  }
  return rows;
}

/**
 * The type column. Named object schemas link to the schema page; enums and
 * scalars render as their JSON type; arrays as `type[]`; maps as
 * `object<string, type>`; unions with ` | `. An unrecognised construct falls
 * back to its JSON type, or `any`.
 */
function typeText(ctx, schema, fallback) {
  if (!schema || typeof schema !== 'object') return fallback || 'any';
  const base = typeOf(ctx, schema, fallback);
  return schema.nullable ? `${base} \\| null` : base;
}

function typeOf(ctx, schema, fallback) {
  if (Array.isArray(schema.oneOf) || Array.isArray(schema.anyOf)) {
    const parts = (schema.oneOf || schema.anyOf).map((s) => typeText(ctx, ctx.effective(s)));
    return [...new Set(parts)].join(' \\| ');
  }
  if (schema.refName && schema.properties) return schemaLink(schema.refName);
  if (schema.type === 'array' || (schema.items && !schema.type)) {
    const items = ctx.effective(schema.items || {});
    const inner = typeText(ctx, items, 'any');
    return inner.includes(' \\| ') || inner.includes('](') ? `${inner}[]` : `${inner}[]`;
  }
  if (schema.properties && !schema.type) return 'object';
  if (schema.type === 'object' || (!schema.type && schema.additionalProperties)) {
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
      return `object<string, ${typeText(ctx, ctx.effective(schema.additionalProperties), 'any')}>`;
    }
    return 'object';
  }
  if (typeof schema.type === 'string') return schema.type;
  if (Array.isArray(schema.type)) return schema.type.join(' \\| ');
  if (Array.isArray(schema.enum)) return typeof schema.enum[0] === 'number' ? 'number' : 'string';
  return fallback || 'any';
}

/** Constraints as one cell: enum, format, bounds, lengths, default, pattern. */
function constraintsText(schema) {
  if (!schema || typeof schema !== 'object') return '';
  const parts = [];
  if (Array.isArray(schema.enum)) parts.push(`one of ${schema.enum.map((v) => `\`${String(v)}\``).join(', ')}`);
  if (schema.format) parts.push(`format \`${schema.format}\``);
  if (schema.pattern) parts.push(`pattern \`${schema.pattern}\``);
  if (schema.minimum !== undefined && schema.maximum !== undefined) parts.push(`${schema.minimum} to ${schema.maximum}`);
  else if (schema.minimum !== undefined) parts.push(`min ${schema.minimum}`);
  else if (schema.maximum !== undefined) parts.push(`max ${schema.maximum}`);
  if (schema.exclusiveMinimum !== undefined && typeof schema.exclusiveMinimum === 'number') parts.push(`> ${schema.exclusiveMinimum}`);
  if (schema.exclusiveMaximum !== undefined && typeof schema.exclusiveMaximum === 'number') parts.push(`< ${schema.exclusiveMaximum}`);
  if (schema.minLength !== undefined && schema.maxLength !== undefined) parts.push(`${schema.minLength} to ${schema.maxLength} chars`);
  else if (schema.minLength !== undefined) parts.push(`min ${schema.minLength} chars`);
  else if (schema.maxLength !== undefined) parts.push(`max ${schema.maxLength} chars`);
  if (schema.minItems !== undefined && schema.maxItems !== undefined) parts.push(`${schema.minItems} to ${schema.maxItems} items`);
  else if (schema.minItems !== undefined) parts.push(`min ${schema.minItems} items`);
  else if (schema.maxItems !== undefined) parts.push(`max ${schema.maxItems} items`);
  if (schema.uniqueItems) parts.push('unique items');
  if (schema.default !== undefined) parts.push(`default \`${JSON.stringify(schema.default)}\``);
  if (schema.deprecated) parts.push('deprecated');
  return parts.join('; ');
}

