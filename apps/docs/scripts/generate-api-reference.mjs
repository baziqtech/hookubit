function schemaLink(name) {
  return `[${name}](./schemas.md#${name.toLowerCase()})`;
}

function errorCodeLink(code) {
  return `[\`${code}\`](./errors.md#${code.replace(/_/g, '-')})`;
}

/** Mirrors VitePress's slugifier for `METHOD \`/path\`` headings. */
function operationAnchor(method, route) {
  return `${method} ${route}`
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, ' ')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
}

/** The `(error.code: \`a\`, \`b\`)` suffix the control plane appends to 4xx descriptions. */
function splitErrorCodes(description) {
  const match = /\s*\(error\.code(?: is one of)?:\s*([^)]*)\)\s*$/.exec(description);
  if (!match) {
    const alone = /^error\.code is one of:\s*(.*)$/.exec(description.trim());
    if (alone) return { text: '', codes: parseCodes(alone[1]) };
    return { text: description.trim(), codes: [] };
  }
  return { text: description.slice(0, match.index).trim(), codes: parseCodes(match[1]) };
}

function parseCodes(list) {
  return [...String(list).matchAll(/`([a-z0-9_]+)`/g)].map((m) => m[1]);
}

function errorCodesIn(description) {
  return splitErrorCodes(String(description || '')).codes;
}

/**
 * Text outside a table cell. Angle brackets outside code spans would otherwise
 * be parsed as HTML (and unknown tags as Vue components); `{{` would be a Vue
 * interpolation. Everything inside backticks is left alone.
 */
function escapeText(text) {
  return String(text)
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{\{/g, '{ {')))
    .join('');
}

/** A table cell: no raw newlines, no unescaped pipes. */
function escapeCell(text) {
  return escapeText(text).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
}

function titleCase(slug) {
  return slug.replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

