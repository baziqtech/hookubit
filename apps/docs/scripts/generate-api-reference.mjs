// Output modes
// ---------------------------------------------------------------------------

/** Files in api/ that carry the marker but are no longer produced. */
function staleGeneratedFiles(pages) {
  if (!fs.existsSync(OUT_DIR)) return [];
  return fs
    .readdirSync(OUT_DIR)
    .filter((name) => name.endsWith('.md') && !pages.has(name))
    .filter((name) => fs.readFileSync(path.join(OUT_DIR, name), 'utf8').startsWith(GENERATED_MARKER))
    .sort();
}

function writePages(pages) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  let written = 0;
  for (const [name, content] of pages) {
    const file = path.join(OUT_DIR, name);
    const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (existing === content) continue;
    fs.writeFileSync(file, content);
    written += 1;
  }
  const stale = staleGeneratedFiles(pages);
  for (const name of stale) fs.unlinkSync(path.join(OUT_DIR, name));

  const parts = [`${pages.size} pages, ${written} written`];
  if (stale.length > 0) parts.push(`${stale.length} stale removed (${stale.join(', ')})`);
  process.stdout.write(`generate-api-reference: ${parts.join(', ')}\n`);
  return 0;
}

/**
 * --check: render into memory and compare with disk. Exit 1 on any difference,
 * naming each file and showing where it first diverges, so the CI log says what
 * to do without anyone re-running the generator locally to find out.
 */
function checkDrift(pages) {
  const problems = [];
  for (const [name, content] of pages) {
    const file = path.join(OUT_DIR, name);
    if (!fs.existsSync(file)) {
      problems.push(`missing: ${rel(file)}`);
      continue;
    }
    const existing = fs.readFileSync(file, 'utf8');
    if (existing !== content) problems.push(`stale: ${rel(file)}\n${firstDifference(existing, content)}`);
  }
  for (const name of staleGeneratedFiles(pages)) {
    problems.push(`orphaned: ${rel(path.join(OUT_DIR, name))} is generated but no longer produced`);
  }

  if (problems.length === 0) {
    process.stdout.write(`generate-api-reference: ${pages.size} pages up to date\n`);
    return 0;
  }
  process.stderr.write(
    `generate-api-reference: the committed API reference does not match ${rel(SOURCE)}\n\n` +
      `${problems.join('\n')}\n\n` +
      'Regenerate and commit the result:\n' +
      '  pnpm --filter @hookubit/docs generate:api\n',
  );
  return 1;
}

/** A small, dependency-free "where does it diverge" for the drift report. */
function firstDifference(onDisk, expected) {
  const a = onDisk.split('\n');
  const b = expected.split('\n');
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i += 1;
  const context = (lines, from, to) =>
    lines
      .slice(Math.max(0, from), Math.min(lines.length, to))
      .map((l) => `      ${l}`)
      .join('\n');
  return [
    `  first difference at line ${i + 1} (on disk ${a.length} lines, expected ${b.length})`,
    '    on disk:',
    context(a, i - 1, i + 3),
    '    expected:',
    context(b, i - 1, i + 3),
  ].join('\n');
}

