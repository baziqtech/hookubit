function main(argv) {
  const check = argv.includes('--check');
  const unknown = argv.filter((a) => a.startsWith('--') && a !== '--check');
  if (unknown.length > 0) fail(`unknown option(s): ${unknown.join(' ')}\nusage: generate-api-reference.mjs [--check]`);

  const document = loadDocument();
  const pages = render(document);

  return check ? checkDrift(pages) : writePages(pages);
}

function fail(message) {
  process.stderr.write(`generate-api-reference: ${message}\n`);
  process.exit(2);
}

function loadDocument() {
  if (!fs.existsSync(SOURCE)) {
    process.stderr.write(
      `generate-api-reference: ${rel(SOURCE)} is missing; emitting it with ` +
        '`pnpm --filter @hookubit/control-api openapi`...\n',
    );
    const result = spawnSync('pnpm', ['--filter', '@hookubit/control-api', 'openapi'], {
      cwd: REPO_ROOT,
      stdio: 'inherit',
    });
    if (result.error || result.status !== 0 || !fs.existsSync(SOURCE)) {
      fail(
        `could not produce ${rel(SOURCE)}.\n` +
          '  The control plane emits it from source: run\n' +
          '    pnpm --filter @hookubit/control-api build && pnpm --filter @hookubit/control-api openapi\n' +
          '  from the repository root, then re-run this script.',
      );
    }
  }

  let raw;
  try {
    raw = fs.readFileSync(SOURCE, 'utf8');
  } catch (err) {
    fail(`cannot read ${rel(SOURCE)}: ${err.message}`);
  }
  let document;
  try {
    document = JSON.parse(raw);
  } catch (err) {
    fail(`${rel(SOURCE)} is not valid JSON: ${err.message}`);
  }
  if (!document || typeof document !== 'object' || !document.paths || typeof document.paths !== 'object') {
    fail(`${rel(SOURCE)} is not an OpenAPI document: no \`paths\` object`);
  }
  if (Object.keys(document.paths).length === 0) {
    fail(`${rel(SOURCE)} has no paths; refusing to generate an empty reference`);
  }
  return document;
}

function rel(file) {
  return path.relative(REPO_ROOT, file);
}

